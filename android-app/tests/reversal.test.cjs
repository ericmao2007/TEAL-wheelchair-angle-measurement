const assert=require('node:assert/strict');
const {ReversalZero,reading}=require('../app/src/main/assets/reversal.js');
const vector=(pitch,roll=0)=>{const p=pitch*Math.PI/180,r=roll*Math.PI/180,g=9.80665;return [g*Math.sin(p),-g*Math.cos(p)*Math.sin(r),g*Math.cos(p)*Math.cos(r)];};
const r=new ReversalZero();
assert(!r.start(null));assert(!r.busy);
assert(r.start(vector(-8)));assert.equal(r.stage,'turn');assert(Math.abs(r.first.pitch+8)<1e-10);
assert(!r.opposite([NaN,0,9]));assert.equal(r.stage,'turn');
assert(r.opposite(vector(12)));assert(r.applied);assert(!r.busy);
assert(Math.abs(r.offset-2)<1e-10);assert(Math.abs(r.result.slope-10)<1e-10);
assert(Math.abs(reading(r.correct(vector(-8))).pitch+10)<1e-10);
assert(Math.abs(reading(r.correct(vector(12,3))).pitch-10)<1e-10);
assert(Math.abs(reading(r.correct(vector(12,3))).roll-3)<1e-10);
r.start(vector(50));r.cancel();assert(r.applied);assert(Math.abs(r.offset-2)<1e-10);
r.start(vector(3));r.opposite(vector(1));assert(Math.abs(r.offset-2)<1e-10);assert(Math.abs(r.result.slope-1)<1e-10);
r.start(vector(2));r.opposite(vector(2));assert.equal(r.result.slope,0);
r.start(vector(-8));r.opposite(vector(12));assert(Math.abs(r.offset-2)<1e-10,'Repeat uses original angles, not old correction');
r.clear();assert.equal(r.offset,0);assert(!r.applied);assert(!r.opposite(vector(12)));
console.log('Reversal: two-click snapshots, immediate average, invalid input, repeat, cancel, Roll and correction passed.');
